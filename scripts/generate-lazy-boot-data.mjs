// Regenerates the lazy boot data modules from their full sources:
//   src/lib/provider-registry-boot.ts  <- src/lib/provider-registry.data.json + provider-registry-maps.ts
//   src/data/theme-boot.ts             <- src/data/themes.ts THEME_OPTIONS
//   src/lib/docs-frontmatter.ts        <- content/docs/** frontmatter (title/description)
// Run after editing either source: node scripts/generate-lazy-boot-data.mjs
// The boot modules must stay tiny: they hold only the fields the boot path
// resolves synchronously (vault key grouping and the active theme palette).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { groupForCategory, vaultProviderForId } from '../src/lib/provider-registry-maps.ts'
import { THEME_OPTIONS } from '../src/data/themes.ts'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

const q = (value) => JSON.stringify(value)

function providerRegistryBoot() {
    const rawProviders = JSON.parse(
        fs.readFileSync(path.join(root, 'src/lib/provider-registry.data.json'), 'utf8')
    )
    const lines = []
    for (const raw of rawProviders) {
        const group = groupForCategory(raw.category)
        if (group === null) continue
        const credentialUrl =
            raw.credentialUrl || (raw.website && raw.website !== '#' ? raw.website : undefined)
        const parts = [
            `id: ${q(raw.id)}`,
            `name: ${q(raw.name)}`,
            `group: ${q(group)}`,
            `vaultProvider: ${q(vaultProviderForId(raw.id))}`,
        ]
        if (credentialUrl) parts.push(`credentialUrl: ${q(credentialUrl)}`)
        lines.push(`    { ${parts.join(', ')} },`)
    }
    return `// Generated by scripts/generate-lazy-boot-data.mjs from provider-registry.data.json. Do not edit.
// Boot-safe subset of the provider registry: only the fields the header vault
// menu resolves synchronously. The full 125-provider catalog stays behind the
// lazy import in provider-registry.ts (used by the vault Add-key picker).
import { resolveRegistryForKey } from './provider-registry-core.ts'
import type { VaultProvider } from '@/types/vault'

export interface BootRegistryProvider {
    id: string
    name: string
    group: string
    vaultProvider: VaultProvider
    credentialUrl?: string
}

// Same first-class entry as provider-registry.ts, mirrored so boot resolution
// matches the full registry exactly.
export const AIOSTREAMS_BOOT_ENTRY: BootRegistryProvider = {
    id: 'aiostreams',
    name: 'AIOStreams',
    group: 'AIOStreams',
    vaultProvider: 'aiostreams',
}

export const CUSTOM_BOOT_ENTRY: BootRegistryProvider = {
    id: 'custom',
    name: 'Other / Custom',
    group: 'Custom',
    vaultProvider: 'other',
}

export const BOOT_CATALOG: BootRegistryProvider[] = [
${lines.join('\n')}
]

export function registryForKey(key: {
    catalogId?: string
    provider: VaultProvider
    customProviderName?: string
}): BootRegistryProvider {
    return resolveRegistryForKey(
        key,
        [AIOSTREAMS_BOOT_ENTRY, ...BOOT_CATALOG, CUSTOM_BOOT_ENTRY],
        BOOT_CATALOG,
        CUSTOM_BOOT_ENTRY
    )
}
`
}

function docsFrontmatter() {
    const docsDir = path.join(root, 'content', 'docs')
    const found = []
    const walk = (dir) => {
        for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
            const p = path.join(dir, e.name)
            if (e.isDirectory()) walk(p)
            else if (/\.(mdx|md)$/.test(e.name)) found.push(p)
        }
    }
    walk(docsDir)
    const unquote = (value) => {
        const trimmed = value.trim()
        if (/^".*"$/.test(trimmed) || /^'.*'$/.test(trimmed)) return trimmed.slice(1, -1)
        return trimmed
    }
    const lines = []
    for (const abs of found.sort()) {
        const rel = path.relative(docsDir, abs).replace(/\\/g, '/')
        let clean = rel.replace(/\.(mdx|md)$/, '')
        if (clean === 'index') clean = ''
        const text = fs.readFileSync(abs, 'utf8')
        const block = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)
        const fm = {}
        if (block) {
            for (const line of block[1].split(/\r?\n/)) {
                const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/)
                if (kv) fm[kv[1]] = unquote(kv[2])
            }
        }
        lines.push(`    ${JSON.stringify(clean)}: ${JSON.stringify({ title: fm.title, description: fm.description })},`)
    }
    return `// Generated by scripts/generate-lazy-boot-data.mjs from content/docs frontmatter. Do not edit.
// Only the sidebar-tree fields (title/description) are kept; MDX bodies load per page.
export interface DocsFrontmatter { title?: string; description?: string }

export const DOCS_FRONTMATTER: Record<string, DocsFrontmatter> = {
${lines.join('\n')}
}
`
}

function themeBoot() {
    const lines = []
    for (const option of THEME_OPTIONS) {
        const paletteKeys = [
            'background',
            'card',
            'cardForeground',
            'primary',
            'primaryForeground',
            'mutedForeground',
            'muted',
            'destructive',
            'destructiveForeground',
            'border',
            'input',
            'ring',
        ]
        const paletteParts = paletteKeys
            .filter((key) => option.palette[key] !== undefined)
            .map((key) => `${key}: ${q(option.palette[key])}`)
        const parts = [`id: ${q(option.id)}`, `palette: { ${paletteParts.join(', ')} }`]
        if (option.logoUrl) parts.push(`logoUrl: ${q(option.logoUrl)}`)
        parts.push(`hasSkin: ${option.customCss ? 'true' : 'false'}`)
        lines.push(`    { ${parts.join(', ')} },`)
    }
    return `// Generated by scripts/generate-lazy-boot-data.mjs from src/data/themes.ts. Do not edit.
// Boot-safe subset of the theme catalog: palette, logo and a skin flag per
// builtin theme so the active theme applies before first paint. Labels, emoji,
// previews and skin CSS load lazily via contexts/ThemeContext.
import type { Theme, ThemePalette } from './theme-core.ts'

export interface BuiltinThemeMeta {
    id: Theme
    palette: ThemePalette
    logoUrl?: string
    hasSkin: boolean
}

export const BUILTIN_THEME_META: BuiltinThemeMeta[] = [
${lines.join('\n')}
]
`
}

const outputs = [
    ['src/lib/provider-registry-boot.ts', providerRegistryBoot()],
    ['src/data/theme-boot.ts', themeBoot()],
    ['src/lib/docs-frontmatter.ts', docsFrontmatter()],
]
for (const [file, content] of outputs) {
    const target = path.join(root, file)
    fs.writeFileSync(target, content)
    console.log(`generated ${file} (${content.length} bytes)`)
}

import { MoreVertical } from 'lucide-react'
import { useUIStore } from '@/store/uiStore'
import { StatusDot } from '@/components/common/StatusDot'
import { AnimatedSettingsIcon } from '@/components/ui/AnimatedIcons'
import { getTimeAgo } from '@/lib/utils'
import { getTagColor } from '@/lib/tag-utils'
import { PlatformSourceChip } from '@/components/addons/PlatformSourceChip'
import { SourceUrlBox } from '@/components/addons/SourceUrlBox'
import { SavedAddonIcon } from './SavedAddonIcon'
import { SavedAddonDeploymentBadge } from './SavedAddonDeploymentBadge'
import type { SavedAddon } from '@/types/saved-addon'
import type { Account } from '@/types/account'

interface SavedAddonCardPreviewProps {
    savedAddon: SavedAddon
    deployedAccounts?: Account[]
    /** Live draft values so the replica tracks the editor fields. */
    name: string
    logo?: string
    description: string
    tags: string[]
    profileName?: string
}

// Read-only replica of the SavedAddonCard for the "Dashboard Preview": the
// real card's classes and pieces with every control inert. On narrow
// viewports it collapses to the compact header row plus description.
export function SavedAddonCardPreview({ savedAddon, deployedAccounts = [], name, logo, description, tags, profileName }: SavedAddonCardPreviewProps) {
    const isPrivacyModeEnabled = useUIStore((state) => state.isPrivacyModeEnabled)

    const displayName = name || savedAddon.manifest.name
    const configurable = !!(savedAddon.manifest.behaviorHints?.configurable || savedAddon.manifest.behaviorHints?.configurationRequired)
    const descriptionText = description || savedAddon.metadata?.customDescription || savedAddon.manifest.description || ''
    const showDescription = !!description || !!(savedAddon.manifest.description && savedAddon.manifest.description !== `Addon generated by ${savedAddon.name}`)
    const health = savedAddon.health

    return (
        <div
            aria-hidden="true"
            inert
            className="pointer-events-none relative flex select-none flex-col rounded-2xl border border-border/40 bg-card p-3 shadow-sm sm:p-5"
        >
            <div className="flex items-start justify-between gap-2">
                <div className="flex min-w-0 flex-1 items-center gap-3">
                    <div className="relative h-11 w-11 shrink-0">
                        <SavedAddonIcon
                            addon={savedAddon}
                            name={displayName}
                            logo={logo || savedAddon.manifest.logo}
                            alt=""
                            className="h-full w-full"
                            textClassName="text-lg text-foreground"
                        />
                        {health && (
                            <StatusDot
                                tone={health.isOnline ? 'success' : 'destructive'}
                                label={health.isOnline ? 'Online' : 'Offline'}
                                pulse={health.isOnline}
                            />
                        )}
                    </div>
                    <div className="flex min-w-0 flex-col pr-2">
                        <span className="truncate text-base font-semibold leading-tight">{displayName}</span>
                        <div className="mt-0.5 flex items-center gap-1.5 overflow-hidden">
                            <span className="truncate text-xs text-muted-foreground/70">v{savedAddon.manifest.version}</span>
                            {configurable && <AnimatedSettingsIcon className="h-3 w-3 text-muted-foreground" />}
                        </div>
                    </div>
                </div>
                <span className="-mr-2 flex h-7 w-7 shrink-0 items-center justify-center text-muted-foreground">
                    <MoreVertical className="h-4 w-4" />
                </span>
            </div>

            {showDescription && descriptionText && (
                <div className="mt-3 line-clamp-2 text-xs leading-relaxed text-muted-foreground">
                    {descriptionText}
                </div>
            )}

            <div className="hidden md:block">
                <SourceUrlBox
                    url={savedAddon.installUrl}
                    manifest={savedAddon.manifest}
                    privacyMode={isPrivacyModeEnabled}
                    variant="compact"
                    disabled
                    className="mt-3"
                />

                {tags.length > 0 && (
                    <div className="mt-2 flex flex-wrap gap-1 pt-1">
                        {tags.map((tag) => {
                            const color = getTagColor(tag)
                            return (
                                <span
                                    key={tag}
                                    data-theme-part="badge"
                                    className="rounded-full px-1.5 py-0 text-xs font-medium leading-5"
                                    style={{ background: color.bg, color: color.text, border: `1px solid ${color.border}` }}
                                >
                                    {tag}
                                </span>
                            )
                        })}
                    </div>
                )}

                <div className="mt-2 flex flex-wrap items-center justify-between gap-2 pt-1">
                    <div className="flex min-w-0 flex-1 items-center gap-1.5">
                        {profileName && (
                            <span className="line-clamp-2 whitespace-normal break-words text-xs text-foreground/60">
                                {profileName}
                            </span>
                        )}
                    </div>
                    <div className="flex max-w-full flex-wrap items-center gap-1.5">
                        {/* Platforms of the accounts that sync this addon, derived only
                            from the deployment summary's matching configured URLs. */}
                        <PlatformSourceChip accounts={deployedAccounts} addon={{ transportUrl: savedAddon.installUrl }} scope="addon" />
                        <SavedAddonDeploymentBadge accounts={deployedAccounts} />
                        {savedAddon.createdAt && (
                            <span className="shrink-0 text-xs tabular-nums text-muted-foreground/60">
                                Added {getTimeAgo(new Date(savedAddon.createdAt))}
                            </span>
                        )}
                    </div>
                </div>
            </div>
        </div>
    )
}

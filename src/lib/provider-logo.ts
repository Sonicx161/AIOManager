const VAULT_PROVIDER_LOGO_IDS: Record<string, string> = { 'real-debrid': 'realdebrid', alldebrid: 'alldebrid', premiumize: 'premiumize', torbox: 'torbox', 'debrid-link': 'debridlink', aiostreams: 'aiostreams', aiometadata: 'aiometadata' }

export function providerLogoPath(input: { catalogId?: string; provider?: string } | string | undefined): string | undefined {
  const id = typeof input === "string" ? input : input?.catalogId || (input?.provider ? VAULT_PROVIDER_LOGO_IDS[input.provider] : undefined)
  const path = id ? PROVIDER_LOGO_PATHS[id] : undefined
  return path ? `${import.meta.env.BASE_URL}${path.slice(1)}` : undefined
}
